/**
 * Plugin integration for SEOPress plugin.
 *
 * @since 4.4.10
 */
class AWPCP_SEOPressPluginIntegration {

    /**
     * @since 4.4.10
     */
    public function setup() {
        add_filter( 'awpcp-should-generate-rel-canonical', array( $this, 'should_generate_rel_canonical' ) );
    }

    /**
     * Let SEOPress print the only canonical URL when its Titles & Metas
     * module, the one that generates the canonical tag, is enabled.
     *
     * @since 4.4.10
     *
     * @param bool $should Whether AWPCP should generate the rel canonical tag.
     *
     * @return bool
     */
    public function should_generate_rel_canonical( $should ) {
        if ( ! function_exists( 'seopress_get_toggle_option' ) || '1' !== (string) seopress_get_toggle_option( 'titles' ) ) {
            return $should;
        }

        add_filter( 'seopress_titles_canonical', array( $this, 'filter_canonical' ) );

        return false;
    }

    /**
     * Use the listing URL as canonical URL on the Show Ad page.
     *
     * @since 4.4.10
     *
     * @param string $html The canonical link tag generated by SEOPress.
     *
     * @return string
     */
    public function filter_canonical( $html ) {
        $awpcp_canonical_url = awpcp_rel_canonical_url();

        if ( $awpcp_canonical_url ) {
            return '<link rel="canonical" href="' . esc_url( $awpcp_canonical_url ) . '">';
        }

        return $html;
    }
}
